import {
  formatPlanHeadingLabel,
  getChargeAmountUsd,
  type BillingInterval,
  type PaidPlanTier,
} from "@/lib/billing/plans";
import { resolvePlanFromServerPriceId } from "@/lib/billing/server-config";

export interface BillingInvoiceItem {
  id: string;
  invoiceNumber: string;
  occurredAtIso: string;
  planLabel: string;
  amountUsd: number;
  status: "paid" | "failed";
  receiptUrl: string;
}

export interface BillingPaymentMethod {
  brand: string;
  last4: string;
  expiry: string | null;
}

export interface BillingEventRow {
  eventId: string;
  eventType: string;
  payload: unknown;
  processedAt: Date;
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function asString(value: unknown): string | null {
  return typeof value === "string" && value.trim().length > 0 ? value.trim() : null;
}

/** Events generated by the local sandbox simulator (never produced by Paddle itself). */
export function isSimulatedBillingEvent(eventId: string): boolean {
  return eventId.startsWith("evt_sdbx_");
}

function formatCardExpiry(month: unknown, year: unknown): string | null {
  if (typeof month !== "number" || typeof year !== "number") return null;
  const mm = String(month).padStart(2, "0");
  const yy = String(year % 100).padStart(2, "0");
  return `${mm}/${yy}`;
}

function prettyCardBrand(raw: string): string {
  const normalized = raw.trim().toLowerCase().replace(/_/g, " ");
  const known: Record<string, string> = {
    visa: "Visa",
    mastercard: "Mastercard",
    american_express: "American Express",
    "american express": "American Express",
    amex: "American Express",
    discover: "Discover",
    diners_club: "Diners Club",
    "diners club": "Diners Club",
    jcb: "JCB",
    maestro: "Maestro",
    unionpay: "UnionPay",
  };
  return known[normalized] ?? normalized.replace(/\b\w/g, (c) => c.toUpperCase());
}

/**
 * Reads the card used for a payment.
 * - Real Paddle `transaction.*` events expose `payments[].method_details.card`.
 * - Simulated events carry a server-generated `custom_data.paymentMethod`.
 * Nothing is ever invented: when Paddle did not tell us, this returns `null` and the UI points
 * the customer to the Paddle portal instead of showing a made-up card.
 */
export function extractPaymentMethod(event: BillingEventRow): BillingPaymentMethod | null {
  const payload = asRecord(event.payload);
  const data = asRecord(payload?.data);
  if (!data) return null;

  if (isSimulatedBillingEvent(event.eventId)) {
    const pm = asRecord(asRecord(data.custom_data)?.paymentMethod);
    const brand = asString(pm?.brand);
    const last4 = asString(pm?.last4);
    return brand && last4
      ? { brand: prettyCardBrand(brand), last4, expiry: asString(pm?.expiry) }
      : null;
  }

  const payments = Array.isArray(data.payments) ? data.payments : [];
  for (const payment of payments) {
    const details = asRecord(asRecord(payment)?.method_details);
    const card = asRecord(details?.card);
    const last4 = asString(card?.last4);
    if (card && last4) {
      return {
        brand: prettyCardBrand(asString(card.type) ?? "card"),
        last4,
        expiry: formatCardExpiry(card.expiry_month, card.expiry_year),
      };
    }
  }
  return null;
}

function realChargeAmountUsd(data: Record<string, unknown>): number | null {
  const totals = asRecord(asRecord(data.details)?.totals);
  const currency = asString(totals?.currency_code) ?? asString(data.currency_code);
  const minorUnits = asString(totals?.grand_total) ?? asString(totals?.total);
  if (currency !== "USD" || !minorUnits || !/^\d+$/.test(minorUnits)) return null;
  return Number.parseInt(minorUnits, 10) / 100;
}

/**
 * Turns stored Paddle notifications into the customer's invoice list.
 *
 * - Real Paddle: exactly one invoice per settled / failed *transaction* (`transaction.completed`,
 *   `transaction.payment_failed|past_due`). `subscription.*` events are lifecycle only, otherwise a
 *   single purchase would list as three invoices.
 * - Simulator: one invoice per simulated activation / failure.
 *
 * `events` must already be scoped to the caller's own subscription / customer ids.
 */
export function buildBillingInvoices(events: BillingEventRow[]): {
  invoices: BillingInvoiceItem[];
  detectedInterval: BillingInterval | null;
  paymentMethod: BillingPaymentMethod | null;
} {
  const invoices: BillingInvoiceItem[] = [];
  const seenInvoiceNumbers = new Set<string>();
  let detectedInterval: BillingInterval | null = null;
  let paymentMethod: BillingPaymentMethod | null = null;

  for (const evt of events) {
    const payload = asRecord(evt.payload);
    const data = asRecord(payload?.data);
    if (!data) continue;

    const simulated = isSimulatedBillingEvent(evt.eventId);
    const isFailure =
      evt.eventType === "transaction.payment_failed" || evt.eventType === "transaction.past_due";
    const isCharge = simulated
      ? evt.eventType === "subscription.activated" ||
        evt.eventType === "subscription.created" ||
        evt.eventType === "transaction.completed" ||
        isFailure
      : evt.eventType === "transaction.completed" || isFailure;
    if (!isCharge) continue;

    if (!isFailure && !paymentMethod) {
      paymentMethod = extractPaymentMethod(evt);
    }

    const customData = asRecord(data.custom_data);
    const items = Array.isArray(data.items) ? data.items : [];
    const firstItem = asRecord(items[0]);
    const priceObj = asRecord(firstItem?.price);
    const mapped = resolvePlanFromServerPriceId(asString(priceObj?.id));
    const cycle = asString(asRecord(priceObj?.billing_cycle)?.interval);

    const interval: BillingInterval =
      mapped?.interval ??
      (cycle === "year" ? "yearly" : cycle === "month" ? "monthly" : null) ??
      (simulated && (customData?.interval === "yearly" || customData?.interval === "annual")
        ? "yearly"
        : "monthly");
    if (!detectedInterval) detectedInterval = interval;

    const plan: PaidPlanTier =
      mapped?.plan ??
      (simulated && (customData?.plan === "team" || customData?.plan === "plus")
        ? customData.plan
        : "pro");
    const seats =
      typeof firstItem?.quantity === "number" && firstItem.quantity >= 1 ? firstItem.quantity : 1;

    const amountUsd =
      (simulated && typeof customData?.amountUsd === "number" ? customData.amountUsd : null) ??
      realChargeAmountUsd(data) ??
      getChargeAmountUsd(plan, interval, seats);

    const providerInvoiceNumber = asString(data.invoice_number);
    const simulatedInvoiceNumber = simulated ? asString(customData?.invoiceNumber) : null;
    const invoiceNumber =
      providerInvoiceNumber ?? simulatedInvoiceNumber ?? `INV-${evt.eventId.slice(-8).toUpperCase()}`;

    // A retried payment re-notifies the same invoice; list it once (newest event wins).
    const dedupeKey = `${invoiceNumber}:${isFailure ? "failed" : "paid"}`;
    if (seenInvoiceNumbers.has(dedupeKey)) continue;
    seenInvoiceNumbers.add(dedupeKey);

    invoices.push({
      id: evt.eventId,
      invoiceNumber,
      occurredAtIso:
        typeof payload?.occurred_at === "string" ? payload.occurred_at : evt.processedAt.toISOString(),
      planLabel: formatPlanHeadingLabel(plan, interval, seats),
      amountUsd,
      status: isFailure ? "failed" : "paid",
      receiptUrl: `/api/paddle/invoices/${encodeURIComponent(evt.eventId)}`,
    });
  }

  return { invoices, detectedInterval, paymentMethod };
}

